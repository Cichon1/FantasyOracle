def caller_lookup(ref_path, games):
    pc = pd.read_csv(ref_path)
    pc = pd.concat([pc, pc[pc["team"] == "LV"].assign(team="OAK")], ignore_index=True)
    g = games[["game_id", "season", "week", "home_team", "away_team"]]
    tg = pd.concat([g.rename(columns={"home_team": "team"}).drop(columns="away_team"),
                    g.rename(columns={"away_team": "team"}).drop(columns="home_team")])
    tg = tg[tg["season"] >= 2018].copy()
    tg["season"] = tg["season"].astype("int64")
    tg["week"] = tg["week"].astype("int64")
    tg = tg.sort_values("week")
    pc = pc.rename(columns={"start_week": "week"})
    pc["season"] = pc["season"].astype("int64")
    pc["week"] = pc["week"].astype("int64")
    pc = pc.sort_values("week")
    m = pd.merge_asof(tg, pc[["team", "season", "week", "play_caller", "confidence"]], on="week",
                      by=["team", "season"], direction="backward")
    return m[["game_id", "team", "season", "week", "play_caller", "confidence"]]


def playcaller_features(df, off_sums, style_sums, games, ref_path):
    cl = caller_lookup(ref_path, games)
    a = off_sums.merge(cl[["game_id", "team", "play_caller"]], on=["game_id", "team"], how="inner")
    s = style_sums[["game_id", "team", "under_center", "under_center_k", "play_action", "pa_k", "heavy_pers",
                    "heavy_pers_k"]]
    a = a.merge(s, on=["game_id", "team"], how="left")
    ratios = {"call_proe": ("proe_sum", "proe_cnt"),
              "call_proe_light_box": ("proe_light_box_sum", "cnt_light_box"),
              "call_proe_heavy_box": ("proe_heavy_box_sum", "cnt_heavy_box"),
              "call_proe_vs_base": ("proe_base_sum", "cnt_base"),
              "call_proe_vs_sub": ("proe_sub_sum", "cnt_sub"),
              "call_under_center_rate": ("under_center", "under_center_k"),
              "call_play_action_rate": ("play_action", "pa_k"),
              "call_heavy_rate": ("heavy_pers", "heavy_pers_k"),
              "call_plays_pg": ("plays", None)}
    a = af.roll(a, "play_caller", ["season", "week"], ratios, halflife=16)
    a = a.sort_values(["play_caller", "season", "week"])
    a["call_games"] = a.groupby("play_caller").cumcount() + 1
    a = af.carry_prior_season(a, "play_caller", ["call_proe_vs_base", "call_proe_vs_sub", "call_heavy_rate"],
                              ["call_proe_light_box", "call_proe_heavy_box"])
    key = df[["game_id", "team", "season", "week"]].merge(cl[["game_id", "team", "play_caller", "confidence"]],
                                                          on=["game_id", "team"], how="left")
    key.index = df.index
    out = af.attach_prior(key, a, "play_caller", "play_caller", list(ratios) + ["call_games"])
    out["call_games"] = out["call_games"].fillna(0)
    # change flags (schedule-known): caller differs from the team's previous game / last season
    cl2 = cl.sort_values(["team", "season", "week"]).copy()
    cl2["prev"] = cl2.groupby("team")["play_caller"].shift(1)
    cl2["call_changed"] = (cl2["play_caller"] != cl2["prev"]).astype(float).where(cl2["prev"].notna())
    last = cl2.groupby(["team", "season"])["play_caller"].last().rename("last_caller").reset_index()
    last["season"] += 1
    cl2 = cl2.merge(last, on=["team", "season"], how="left")
    cl2["call_new_this_season"] = (cl2["play_caller"] != cl2["last_caller"]).astype(float).where(cl2["last_caller"].notna())
    cl2["call_games_with_team"] = cl2.groupby(["team", "play_caller"]).cumcount()
    x = df[["game_id", "team"]].merge(cl2[["game_id", "team", "call_changed", "call_new_this_season",
                                           "call_games_with_team"]], on=["game_id", "team"], how="left")
    for c in ["call_changed", "call_new_this_season", "call_games_with_team"]:
        out[c] = x[c].values
    out["call_low_confidence"] = (key["confidence"] == "medium").astype(float)
    return out
