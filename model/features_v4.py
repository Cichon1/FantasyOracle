OL = {"T", "G", "C", "OL", "OT", "OG"}
DB = {"CB", "S", "SS", "FS", "DB"}
FRONT = {"DE", "DT", "DL", "NT", "LB", "OLB", "ILB", "MLB", "EDGE"}


def provisional_teams(data_dir, stats, S, W):
    """Teams whose week-W game isn't played yet and whose final injury report isn't out yet (it posts two days
    before the game: Friday for Sunday games). Only these get the midweek-practice handling."""
    g = pd.read_parquet(os.path.join(data_dir, "games.parquet"))
    g = g[(g["season"] == S) & (g["week"] == W)]
    done = set(stats.loc[(stats["season"] == S) & (stats["week"] == W), "team"])
    today = pd.Timestamp.now(tz="America/New_York").normalize().tz_localize(None)
    pend = g[pd.to_datetime(g["gameday"]) - pd.Timedelta(days=2) > today]
    return (set(pend["home_team"]) | set(pend["away_team"])) - done


def attach_injury_final(df, data_dir, players, stats, upcoming_week):
    inj = pd.concat([pd.read_parquet(f, columns=["season", "week", "team", "gsis_id", "position", "report_status",
                                                  "practice_status"])
                     for f in sorted(glob.glob(os.path.join(data_dir, "inj", "*.parquet")))], ignore_index=True)
    inj = inj.rename(columns={"gsis_id": "player_id"}).drop_duplicates(["player_id", "season", "week"], keep="last")
    st = inj["report_status"].fillna("")
    if upcoming_week is not None:
        # final statuses come out Friday; until then use practice as a provisional status
        S, W = upcoming_week
        prov = provisional_teams(data_dir, stats, S, W)
        cur = (inj["season"] == S) & (inj["week"] == W) & (st == "") & inj["team"].isin(prov)
        ps = inj["practice_status"].fillna("")
        # a midweek DNP is not a final "Doubtful" (training only ever sees final statuses, where Doubtful
        # almost always means sitting); the usual Friday outcome for a midweek DNP or limited player is Questionable
        st = st.mask(cur & ps.str.startswith("Did Not"), "Questionable")
        st = st.mask(cur & ps.str.startswith("Limited"), "Questionable")
    inj["status"] = st
    inj["out_or_d"] = st.isin(["Out", "Doubtful"]).astype(float)
    # opportunity / snap state going into the week (after each player's last game)
    s2 = stats.sort_values(["player_id", "season", "week"]).copy()
    for c in ["target_share", "carry_share"]:
        s2[f"{c}_state"] = fo.gewm(s2[c], s2["player_id"], 4)
    sn = pd.concat([pd.read_parquet(f, columns=["pfr_player_id", "season", "week", "offense_pct", "defense_pct"])
                    for f in sorted(glob.glob(os.path.join(data_dir, "snaps", "*.parquet")))], ignore_index=True)
    sn = sn.merge(players[["pfr_id", "gsis_id"]].dropna().drop_duplicates("pfr_id"), left_on="pfr_player_id",
                  right_on="pfr_id").rename(columns={"gsis_id": "player_id"})
    sn = sn.groupby(["player_id", "season", "week"], as_index=False)[["offense_pct", "defense_pct"]].max()
    sn = sn.sort_values(["player_id", "season", "week"])
    for c in ["offense_pct", "defense_pct"]:
        sn[f"{c}_state"] = fo.gewm(sn[c], sn["player_id"], 3)
    flagged = inj[inj["out_or_d"] == 1][["player_id", "team", "season", "week", "position"]].copy()
    flagged = flagged.join(af.attach_prior(flagged, s2, "player_id", "player_id", ["target_share_state", "carry_share_state"]))
    flagged = flagged.join(af.attach_prior(flagged, sn, "player_id", "player_id", ["offense_pct_state", "defense_pct_state"]))
    flagged = flagged.fillna({"target_share_state": 0, "carry_share_state": 0, "offense_pct_state": 0, "defense_pct_state": 0})
    flagged["ol_starter"] = (flagged["position"].isin(OL) & (flagged["offense_pct_state"] >= 0.6)).astype(float)
    flagged["db_starter"] = (flagged["position"].isin(DB) & (flagged["defense_pct_state"] >= 0.6)).astype(float)
    flagged["front_starter"] = (flagged["position"].isin(FRONT) & (flagged["defense_pct_state"] >= 0.6)).astype(float)
    agg = flagged.groupby(["team", "season", "week"], as_index=False).agg(
        ij_vacated_tgt=("target_share_state", "sum"), ij_vacated_car=("carry_share_state", "sum"),
        ij_ol_starters_out=("ol_starter", "sum"), _db=("db_starter", "sum"), _front=("front_starter", "sum"))
    out = pd.DataFrame(index=df.index)
    x = df[["team", "season", "week"]].merge(agg, on=["team", "season", "week"], how="left")
    for c in ["ij_vacated_tgt", "ij_vacated_car", "ij_ol_starters_out"]:
        out[c] = x[c].fillna(0).values
    y = df[["opponent_team", "season", "week"]].merge(
        agg[["team", "season", "week", "_db", "_front"]].rename(columns={"team": "opponent_team"}),
        on=["opponent_team", "season", "week"], how="left")
    out["ij_opp_db_starters_out"] = y["_db"].fillna(0).values
    out["ij_opp_front_starters_out"] = y["_front"].fillna(0).values
    own = df[["player_id", "season", "week"]].merge(inj[["player_id", "season", "week", "status"]],
                                                    on=["player_id", "season", "week"], how="left")["status"].fillna("")
    out["ij_questionable"] = (own == "Questionable").astype(float).values
    out["ij_doubtful"] = (own == "Doubtful").astype(float).values
    # remove the player's own share from "vacated"
    own_state = af.attach_prior(df, s2, "player_id", "player_id", ["target_share_state", "carry_share_state"])
    selfd = (own.values == "Doubtful") | (own.values == "Out")
    out["ij_vacated_tgt"] = (out["ij_vacated_tgt"] - own_state["target_share_state"].fillna(0).where(selfd, 0)).clip(lower=0)
    out["ij_vacated_car"] = (out["ij_vacated_car"] - own_state["carry_share_state"].fillna(0).where(selfd, 0)).clip(lower=0)
    return out


