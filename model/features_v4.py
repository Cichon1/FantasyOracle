def protection_and_qb(data_dir, df, games, depth_qb=None, out_ids=None, upcoming_week=None):
    p = load_pbp(data_dir, ["game_id", "play_id", "season", "week", "season_type", "posteam", "defteam", "qb_dropback",
                            "sack", "qb_hit", "passer_player_id", "epa", "qb_spike"])
    p = p[(p["qb_dropback"] == 1) & (p["qb_spike"] != 1)]
    part = pd.concat([pd.read_parquet(f, columns=["nflverse_game_id", "play_id", "was_pressure"])
                      for f in sorted(glob.glob(os.path.join(data_dir, "part", "part_*.parquet")))], ignore_index=True)
    part = part.rename(columns={"nflverse_game_id": "game_id"})
    part["play_id"] = part["play_id"].astype(int)
    p = p.merge(part, on=["game_id", "play_id"], how="left")
    p["pr"] = p["was_pressure"].astype(float)
    p["pr_k"] = p["pr"].notna().astype(float)
    p["one"] = 1.0
    keys = ["game_id", "season", "week"]
    o = p.groupby(keys + ["posteam"], as_index=False)[["one", "sack", "qb_hit", "pr", "pr_k"]].sum().rename(columns={"posteam": "team"})
    d = p.groupby(keys + ["defteam"], as_index=False)[["one", "sack", "qb_hit", "pr", "pr_k"]].sum().rename(columns={"defteam": "team"})
    o = af.roll(o, "team", ["season", "week"], {"pp_sack_rate_allowed": ("sack", "one"), "pp_hit_rate_allowed": ("qb_hit", "one"),
                                                 "pp_pressure_allowed": ("pr", "pr_k")}, halflife=8)
    d = af.roll(d, "team", ["season", "week"], {"pp_def_sack_rate": ("sack", "one"), "pp_def_hit_rate": ("qb_hit", "one"),
                                                 "pp_def_pressure_rate": ("pr", "pr_k")}, halflife=8)
    o = af.carry_prior_season(o, "team", ["pp_pressure_allowed"])
    d = af.carry_prior_season(d, "team", ["pp_def_pressure_rate"])
    out = pd.DataFrame(index=df.index)
    out = out.join(af.attach_prior(df, o, "team", "team", ["pp_sack_rate_allowed", "pp_hit_rate_allowed", "pp_pressure_allowed"]))
    out = out.join(af.attach_prior(df, d, "opponent_team", "team", ["pp_def_sack_rate", "pp_def_hit_rate", "pp_def_pressure_rate"]))
    out["pp_sack_matchup"] = out["pp_sack_rate_allowed"] * out["pp_def_sack_rate"]
    out["pp_pressure_matchup"] = out["pp_pressure_allowed"] * out["pp_def_pressure_rate"]

    # QB starters: passer with the most dropbacks in each team-game
    qb = p[p["passer_player_id"].notna()].groupby(keys + ["posteam", "passer_player_id"]).agg(
        n=("one", "sum"), epa=("epa", "sum")).reset_index()
    starters = qb.sort_values("n").groupby(["game_id", "posteam"]).tail(1)[["game_id", "season", "week", "posteam",
                                                                             "passer_player_id"]]
    starters = starters.rename(columns={"posteam": "team", "passer_player_id": "qb_id"})
    # Projected (pre-game) starter for every team-game: depth-chart QB1 not ruled Out that week;
    # if there's no depth chart, the team's previous starter. The actual starter is only used for history.
    qd = qb_depth_table(data_dir, games)
    inj = pd.concat([pd.read_parquet(f, columns=["season", "week", "gsis_id", "report_status"])
                     for f in sorted(glob.glob(os.path.join(data_dir, "inj", "*.parquet")))], ignore_index=True)
    outs = set(map(tuple, inj.loc[inj["report_status"] == "Out", ["season", "week", "gsis_id"]].values.tolist()))
    if out_ids and upcoming_week is not None:
        outs |= {(upcoming_week[0], upcoming_week[1], q) for q in out_ids}
    qd = qd[[(a, b, c) not in outs for a, b, c in zip(qd["season"], qd["week"], qd["qb_id"])]]
    qd = qd.sort_values(["season", "week", "team", "depth"]).groupby(["season", "week", "team"]).head(1)
    g2 = games[["game_id", "season", "week", "home_team", "away_team"]]
    tg = pd.concat([g2.rename(columns={"home_team": "team"}).drop(columns="away_team"),
                    g2.rename(columns={"away_team": "team"}).drop(columns="home_team")])
    tg = tg[tg["season"] >= 2018]
    proj = tg.merge(qd[["season", "week", "team", "qb_id"]], on=["season", "week", "team"], how="left")
    act = starters[["game_id", "team", "qb_id"]].rename(columns={"qb_id": "actual_qb"})
    proj = proj.merge(act, on=["game_id", "team"], how="left").sort_values(["team", "season", "week"])
    proj["prev_actual"] = proj.groupby("team")["actual_qb"].transform(lambda x: x.ffill().shift(1))
    proj["proj_qb"] = proj["qb_id"].fillna(proj["prev_actual"])
    proj["qb_changed"] = (proj["proj_qb"] != proj["prev_actual"]).astype(float).where(proj["prev_actual"].notna())
    projected = proj[["game_id", "season", "week", "team", "proj_qb", "qb_changed", "actual_qb"]]
    # QB track record (state after each of his games)
    qs = qb.rename(columns={"passer_player_id": "qb_id"}).sort_values(["qb_id", "season", "week"])
    qs["start"] = qs.set_index(["game_id", "posteam", "qb_id"]).index.isin(
        starters.set_index(["game_id", "team", "qb_id"]).index).astype(float)
    qs = af.roll(qs, "qb_id", ["season", "week"], {"qb_epa_per_db": ("epa", "n"), "qb_db_pg": ("n", None)}, halflife=16)
    qs["qb_career_starts"] = qs.groupby("qb_id")["start"].cumsum()
    sx = df[["game_id", "team", "season", "week"]].merge(
        projected[["game_id", "team", "proj_qb", "qb_changed"]].rename(columns={"proj_qb": "qb_id"}),
        on=["game_id", "team"], how="left")
    sx.index = df.index
    out["qb_changed"] = sx["qb_changed"]
    tmp = sx[["qb_id", "season", "week"]].rename(columns={"qb_id": "player_id"})
    qprior = af.attach_prior(tmp, qs.rename(columns={"qb_id": "player_id"}), "player_id", "player_id",
                             ["qb_epa_per_db", "qb_db_pg", "qb_career_starts"])
    out["qb_starter_epa"] = qprior["qb_epa_per_db"]
    out["qb_starter_db_pg"] = qprior["qb_db_pg"]
    out["qb_starter_starts"] = qprior["qb_career_starts"].fillna(0)
    out["qb_is_projected_starter"] = (df["player_id"] == sx["qb_id"]).astype(float).where(df["position"] == "QB")
    # receiver's target share with this specific QB
    act = df[["game_id", "team"]].merge(starters[["game_id", "team", "qb_id"]], on=["game_id", "team"], how="left")
    act.index = df.index
    st = df[["player_id", "season", "week", "target_share"]].join(act[["qb_id"]])
    st = st[~df["upcoming"] & ~df["phantom"]].dropna(subset=["qb_id"])
    st["pq"] = st["player_id"] + "|" + st["qb_id"]
    st["one"] = 1.0
    st = af.roll(st, "pq", ["season", "week"], {"qb_tgt_share_with_qb": ("target_share", None)}, halflife=8)
    st = st.sort_values(["pq", "season", "week"])
    st["qb_games_with_qb"] = st.groupby("pq").cumcount() + 1
    key = df[["player_id", "season", "week"]].join(sx[["qb_id"]])
    key["pq"] = key["player_id"] + "|" + key["qb_id"].fillna("")
    out = out.join(af.attach_prior(key, st, "pq", "pq", ["qb_tgt_share_with_qb", "qb_games_with_qb"]))
    out["qb_games_with_qb"] = out["qb_games_with_qb"].fillna(0)
    return out, sx["qb_id"]


