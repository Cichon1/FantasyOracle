def context_features(df, games, data_dir):
    g = games.copy()
    out = pd.DataFrame(index=df.index)
    x = df[["game_id", "team", "opponent_team"]].merge(
        g[["game_id", "home_team", "stadium_id", "location", "weekday", "gametime", "surface", "referee", "home_rest",
           "away_rest"]], on="game_id", how="left")
    is_home = (x["team"] == x["home_team"]).values
    rest = np.where(is_home, x["home_rest"], x["away_rest"])
    out["ctx_short_week"] = (pd.Series(rest, index=df.index) <= 5).astype(float)
    out["ctx_thursday"] = (x["weekday"] == "Thursday").astype(float).values
    hour = pd.to_numeric(x["gametime"].str.slice(0, 2), errors="coerce")
    out["ctx_prime_time"] = ((hour >= 19) | x["weekday"].isin(["Monday", "Thursday"])).astype(float).values
    stadium_tz = x["stadium_id"].map(INTL_TZ).fillna(x["home_team"].map(TEAM_TZ))
    out["ctx_tz_travel"] = (stadium_tz - x["team"].map(TEAM_TZ)).abs().values
    out["ctx_international"] = x["stadium_id"].isin(INTL_TZ).astype(float).values
    out["ctx_turf"] = (~x["surface"].fillna("").str.strip().isin(["grass", "dessograss", ""])).astype(float).values
    out["ctx_altitude"] = (x["stadium_id"] == "DEN00").astype(float).values
    # referee crew: penalties per game, prior games only
    p = load_pbp(data_dir, ["game_id", "play_id", "season", "week", "season_type", "penalty"])
    pen = p.groupby(["game_id", "season", "week"], as_index=False)["penalty"].sum()
    pen = pen.merge(g[["game_id", "referee"]], on="game_id").dropna(subset=["referee"])
    pen = af.roll(pen, "referee", ["season", "week"], {"ctx_ref_penalties_pg": ("penalty", None)}, halflife=16)
    tmp = df[["season", "week"]].assign(referee=x["referee"].values)
    out["ctx_ref_penalties_pg"] = af.attach_prior(tmp, pen, "referee", "referee", ["ctx_ref_penalties_pg"])["ctx_ref_penalties_pg"]
    return out


