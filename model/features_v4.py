def depth_table(data_dir, games):
    rows = []
    g = games[["game_id", "season", "week", "gameday", "home_team", "away_team"]].copy()
    g["gameday"] = pd.to_datetime(g["gameday"])
    tg = pd.concat([g.rename(columns={"home_team": "team"}).drop(columns="away_team"),
                    g.rename(columns={"away_team": "team"}).drop(columns="home_team")])
    for f in sorted(glob.glob(os.path.join(data_dir, "depth", "depth_*.parquet"))):
        d = pd.read_parquet(f)
        if "dt" not in d.columns:
            d = d[(d["formation"] == "Offense") & d["position"].isin(SKILL + ["FB"])]
            d = d.assign(depth=pd.to_numeric(d["depth_team"], errors="coerce"), team=d["club_code"])
            d = d.dropna(subset=["week", "gsis_id"])
            d["week"] = d["week"].astype(int)
            d = d.groupby(["gsis_id", "season", "week", "team"], as_index=False)["depth"].min()
            rows.append(d.rename(columns={"gsis_id": "player_id"}))
        else:
            d = d[d["pos_abb"].isin(SKILL + ["FB"])].copy()
            d["dt"] = pd.to_datetime(d["dt"]).dt.tz_localize(None)
            snaps = d.groupby(["team", "dt"]).size().reset_index()[["team", "dt"]].sort_values("dt")
            tgs = tg.sort_values("gameday")
            m = pd.merge_asof(tgs, snaps.rename(columns={"dt": "snap"}), left_on="gameday", right_on="snap",
                              by="team", direction="backward", allow_exact_matches=False)
            m = m.dropna(subset=["snap"])
            m = m[(m["gameday"] - m["snap"]).dt.days <= 10]
            dd = d.rename(columns={"dt": "snap"}).merge(m[["team", "snap", "season", "week"]], on=["team", "snap"])
            dd = dd.groupby(["gsis_id", "season", "week", "team"], as_index=False)["pos_rank"].min()
            rows.append(dd.rename(columns={"gsis_id": "player_id", "pos_rank": "depth"}))
    dt = pd.concat(rows, ignore_index=True)
    dt = dt.groupby(["player_id", "season", "week"], as_index=False)["depth"].min()
    return dt


def qb_depth_table(data_dir, games):
    """Pre-game QB depth order per team-week: weekly depth charts (2018-2024), and for 2025+ the
    latest snapshot before each game."""
    g = games[["game_id", "season", "week", "gameday", "home_team", "away_team"]].copy()
    g["gameday"] = pd.to_datetime(g["gameday"])
    tg = pd.concat([g.rename(columns={"home_team": "team"}).drop(columns="away_team"),
                    g.rename(columns={"away_team": "team"}).drop(columns="home_team")])
    rows = []
    for f in sorted(glob.glob(os.path.join(data_dir, "depth", "depth_*.parquet"))):
        d = pd.read_parquet(f)
        if "dt" not in d.columns:
            d = d[(d["formation"] == "Offense") & (d["position"] == "QB")].dropna(subset=["week", "gsis_id"])
            d = d.assign(depth=pd.to_numeric(d["depth_team"], errors="coerce"), team=d["club_code"],
                         week=d["week"].astype(int))
            rows.append(d.groupby(["season", "week", "team", "gsis_id"], as_index=False)["depth"].min())
        else:
            d = d[d["pos_abb"] == "QB"].copy()
            d["dt"] = pd.to_datetime(d["dt"]).dt.tz_localize(None)
            snaps = d.groupby(["team", "dt"]).size().reset_index()[["team", "dt"]].sort_values("dt")
            m = pd.merge_asof(tg.sort_values("gameday"), snaps.rename(columns={"dt": "snap"}), left_on="gameday",
                              right_on="snap", by="team", direction="backward", allow_exact_matches=False)
            m = m.dropna(subset=["snap"])
            m = m[(m["gameday"] - m["snap"]).dt.days <= 10]
            dd = d.rename(columns={"dt": "snap"}).merge(m[["team", "snap", "season", "week"]], on=["team", "snap"])
            rows.append(dd.groupby(["season", "week", "team", "gsis_id"], as_index=False)["pos_rank"].min()
                        .rename(columns={"pos_rank": "depth"}))
    q = pd.concat(rows, ignore_index=True).rename(columns={"gsis_id": "qb_id"})
    return q.groupby(["season", "week", "team", "qb_id"], as_index=False)["depth"].min()


def attach_depth(df, data_dir, games):
    dt = depth_table(data_dir, games)
    x = df[["player_id", "season", "week"]].merge(dt, on=["player_id", "season", "week"], how="left")
    out = pd.DataFrame(index=df.index)
    out["dc_depth_rank"] = x["depth"].values
    out["dc_is_starter"] = (out["dc_depth_rank"] == 1).astype(float).where(out["dc_depth_rank"].notna())
    # change vs the player's previous game with a depth listing
    tmp = df[["player_id", "season", "week"]].assign(depth=out["dc_depth_rank"].values)
    tmp = tmp.sort_values(["player_id", "season", "week"])
    prev = fo.gffill_shift(tmp["depth"], tmp["player_id"])
    out.loc[tmp.index, "dc_depth_change"] = (tmp["depth"] - prev).values
    out["dc_promoted"] = (out["dc_depth_change"] < 0).astype(float).where(out["dc_depth_change"].notna())
    out["dc_demoted"] = (out["dc_depth_change"] > 0).astype(float).where(out["dc_depth_change"].notna())
    return out


